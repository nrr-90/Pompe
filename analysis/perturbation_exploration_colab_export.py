adata = ad.read_h5ad(
    "/content/drive/MyDrive/MultiCausGRN/causal_extension/Frangieh_2021.h5ad",
    backed="r"
)

obs = adata.obs[["sgRNA", "condition"]].copy()
obs["TF"] = (
    obs["sgRNA"].astype(str)
    .str.replace(r"_\d+$", "", regex=True)
    .str.upper()
)

genes = pd.Index(adata.var_names.astype(str).str.upper())

control_idx = np.flatnonzero((
    (obs["condition"] == "Control") &
    obs["TF"].isin(["NO_SITE", "ONE_NON-GENE_SITE"])
).to_numpy())

rng = np.random.default_rng(42)
background_results = []

def expression_means(indices, columns):
    X = adata.X[indices, :][:, columns]
    if sparse.issparse(X):
        return np.asarray(X.mean(axis=0)).ravel()
    return np.asarray(X).mean(axis=0)

for tf, group in de.groupby("TF"):
    # Sample nonresponsive predictions across the TF score range
    background = group[~group["supported"].astype(bool)].copy()

    background["score_bin"] = pd.qcut(
        background["score"].rank(method="first"),
        q=10,
        labels=False,
        duplicates="drop"
    )

    samples = []
    for _, bin_group in background.groupby("score_bin"):
        n = min(10, len(bin_group))
        samples.append(
            bin_group.sample(
                n=n,
                random_state=42
            )
        )

    selected = pd.concat(samples).copy()

    cols = genes.get_indexer(
        selected["Target"].astype(str).str.upper()
    )

    valid = cols >= 0
    selected = selected.iloc[np.flatnonzero(valid)]
    cols = cols[valid]

    control_means = expression_means(control_idx, cols)

    guides = sorted(obs.loc[
        (obs["condition"] == "Control") &
        (obs["TF"] == tf),
        "sgRNA"
    ].unique())

    if len(guides) != 3:
        print(tf, "skipped: expected 3 guides")
        continue

    effects = []

    for guide in guides:
        idx = np.flatnonzero((
            (obs["condition"] == "Control") &
            (obs["sgRNA"] == guide)
        ).to_numpy())

        guide_means = expression_means(idx, cols)
        effects.append(guide_means - control_means)

    effects = np.asarray(effects)

    for j, (_, edge) in enumerate(selected.iterrows()):
        values = effects[:, j]

        # All guides must agree in direction.
        # Zero effects do not count as agreement.
        all_consistent = bool(
            np.all(values > 0) or np.all(values < 0)
        )

        background_results.append({
            "TF": tf,
            "Target": edge["Target"],
            "score": edge["score"],
            "guide_1_effect": values[0],
            "guide_2_effect": values[1],
            "guide_3_effect": values[2],
            "all_three_consistent": all_consistent
        })

    print(tf, "background completed:", len(selected))

background_df = pd.DataFrame(background_results)

# Use the same directional-consistency definition
# for responsive and background edges
responsive_consistent = int(
    guide_results["all_three_consistent"].astype(bool).sum()
)
responsive_total = len(guide_results)

background_consistent = int(
    background_df["all_three_consistent"].sum()
)
background_total = len(background_df)

contingency = [
    [
        responsive_consistent,
        responsive_total - responsive_consistent
    ],
    [
        background_consistent,
        background_total - background_consistent
    ]
]

odds_ratio, pvalue = fisher_exact(
    contingency,
    alternative="greater"
)

