# ============================================
# 1. Original discovery ranking
# ============================================

discovery = pd.read_csv(
    DISCOVERY,
    usecols=["TF", "Target", "score"]
)

discovery["TF"] = discovery["TF"].astype(str).str.upper()
discovery["Target"] = discovery["Target"].astype(str).str.upper()

discovery = discovery.sort_values(
    "score",
    ascending=False,
    kind="stable"
).reset_index(drop=True)

discovery["discovery_rank"] = np.arange(
    1, len(discovery) + 1
)

# Only top 10,000 needed
top = discovery.head(10000).copy()

# ============================================
# 2. Existing Norman perturbation results
# ============================================

norman = pd.read_csv(
    NORMAN_RESULTS,
    usecols=[
        "TF", "Target",
        "Norman_logFC",
        "Norman_p",
        "Norman_FDR",
        "n_perturbed_cells",
        "n_control_cells"
    ]
)

norman["TF"] = norman["TF"].astype(str).str.upper()
norman["Target"] = norman["Target"].astype(str).str.upper()

# Ensure unique TF-target results
assert not norman.duplicated(["TF", "Target"]).any(), (
    "Duplicate TF-target perturbation results detected."
)

# ============================================
# 3. Merge with top-ranked predictions
# ============================================

merged = top.merge(
    norman,
    on=["TF", "Target"],
    how="left",
    validate="one_to_one",
    indicator=True
)

merged["testable"] = merged["_merge"].eq("both")

merged["supported"] = (
    merged["testable"]
    & (merged["Norman_FDR"] < 0.05)
    & (merged["Norman_logFC"].abs() >= 0.10)
)

# ============================================
# 4. Summary by discovery cutoff
# ============================================

summary = []

for n in [1000, 5000, 10000]:

    subset = merged[merged["discovery_rank"] <= n]

    testable = subset[subset["testable"]]
    supported = subset[subset["supported"]]

    summary.append({
        "Top_N": n,
        "Testable": len(testable),
        "Supported": len(supported),
        "Support_Rate_Percent": round(
            100 * len(supported) / len(testable), 2
        ) if len(testable) else np.nan,
        "Testable_TFs": testable["TF"].nunique(),
        "Supported_TFs": supported["TF"].nunique()
    })

summary = pd.DataFrame(summary)

print("====================================")
print("NORMAN TOP-RANK VALIDATION SUMMARY")
