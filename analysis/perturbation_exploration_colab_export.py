import os
import numpy as np
import pandas as pd
import anndata as ad
from scipy import sparse
from scipy.stats import mannwhitneyu
from statsmodels.stats.multitest import multipletests

path = "/content/drive/MyDrive/MultiCausGRN/causal_extension/Frangieh_2021.h5ad"
outdir = "/content/drive/MyDrive/MultiCausGRN_Pompe/Perturbation_Validation/Frangieh2021"
os.makedirs(outdir, exist_ok=True)

tfs = [
    "E2F1", "FOS", "FOXM1", "IRF3", "IRF4", "KLF4",
    "MYC", "SMAD3", "SMAD4", "SOX4", "SP100",
    "STAT1", "STAT3", "TFAP2A", "TP53", "TSC22D3"
]

adata = ad.read_h5ad(path, backed="r")

obs = adata.obs[["sgRNA", "condition"]].copy()
obs["target"] = (
    obs["sgRNA"].astype(str)
    .str.replace(r"_\d+$", "", regex=True)
    .str.upper()
)

control_targets = {"NO_SITE", "ONE_NON-GENE_SITE"}
condition = "Control"

control_mask = (
    (obs["condition"] == condition) &
    obs["target"].isin(control_targets)
).to_numpy()

# Use counts if available, otherwise X
layer = "counts" if "counts" in adata.layers else None
print("Expression source:", layer if layer else "X")
print("Control cells:", control_mask.sum())

gene_names = pd.Index(adata.var_names.astype(str).str.upper())

# Restrict analysis to targets predicted for these TFs
pred = network[
    network["TF"].astype(str).str.upper().isin(tfs)
].copy()
pred["TF"] = pred["TF"].str.upper()
pred["Target"] = pred["Target"].str.upper()
pred = pred[pred["Target"].isin(gene_names)]

gene_indices = gene_names.get_indexer(
    pd.Index(pred["Target"].unique())
)
gene_indices = gene_indices[gene_indices >= 0]
selected_genes = gene_names[gene_indices]

def get_matrix(mask):
    idx = np.flatnonzero(mask)
    X = (
        adata.layers[layer][idx, :][:, gene_indices]
        if layer else adata.X[idx, :][:, gene_indices]
    )
    return X.toarray() if sparse.issparse(X) else np.asarray(X)

X_ctrl = get_matrix(control_mask)
results = []

for tf in tfs:
    mask = (
        (obs["condition"] == condition) &
        (obs["target"] == tf)
    ).to_numpy()

    n = int(mask.sum())
    if n < 20:
        print(tf, "skipped: insufficient cells", n)
        continue

    X_pert = get_matrix(mask)

    # Normalize each cell to counts per 10,000 and log1p
    def normalize(X):
        totals = X.sum(axis=1, keepdims=True)
        return np.log1p(
            X / np.maximum(totals, 1) * 10000
        )

    A = normalize(X_pert)
    B = normalize(X_ctrl)

    tf_edges = pred[pred["TF"] == tf]
    target_set = set(tf_edges["Target"])

    for j, gene in enumerate(selected_genes):
        if gene not in target_set:
            continue

        p = mannwhitneyu(
            A[:, j], B[:, j],
            alternative="two-sided"
        ).pvalue

        effect = float(A[:, j].mean() - B[:, j].mean())

        results.append({
            "TF": tf,
            "Target": gene,
            "n_perturbed": n,
            "n_control": len(B),
            "mean_log_expression_difference": effect,
            "pvalue": p
        })

    print(tf, "completed:", n, "perturbed cells")

df = pd.DataFrame(results)

if not df.empty:
    df["FDR"] = np.nan
    for tf, indices in df.groupby("TF").groups.items():
        df.loc[indices, "FDR"] = multipletests(
            df.loc[indices, "pvalue"],
            method="fdr_bh"
        )[1]

    df = df.merge(
        pred[["TF", "Target", "score"]],
        on=["TF", "Target"],
        how="left"
    )

    df["supported"] = (
        (df["FDR"] < 0.05) &
        (df["mean_log_expression_difference"].abs() >= 0.1)
    )

    output = os.path.join(
        outdir, "Frangieh_Control_TF_Perturbation_DE.csv"
    )
    df.to_csv(output, index=False)

    print("\n=== SUMMARY ===")
    print("Tested edges:", len(df))
    print("Supported edges:", df["supported"].sum())
    print("Support rate:", round(100 * df["supported"].mean(), 2), "%")
    print("\nBy TF:")
    print(df.groupby("TF")["supported"].agg(["sum", "count"]))
    print("\nSaved:", output)

