import scanpy as sc
import pandas as pd
import numpy as np
from scipy import sparse
from scipy.stats import mannwhitneyu

DIXIT = (
    "/content/drive/MyDrive/MultiCausGRN/"
    "causal_extension/Dixit_2016_raw.h5ad"
)

adata = sc.read_h5ad(DIXIT, backed="r")

obs = adata.obs[["guide", "batch"]].copy()
obs["guide"] = obs["guide"].astype(str)

TF_LIST = [
    "CREB1", "E2F4", "EGR1", "ELF1", "ELK1",
    "ETS1", "GABPA", "IRF1", "NR2C2", "YY1"
]

# Single TF guides only
obs["TF"] = obs["guide"].str.extract(
    r"^sg([A-Za-z0-9]+)_\d+$",
    expand=False
).str.upper()

# Single intergenic guides only
control_mask = obs["guide"].str.fullmatch(
    r"INTERGENIC\d+",
    na=False
)

gene_symbols = (
    adata.var["gene_symbols"]
    .astype(str)
    .str.upper()
)

results = []

for tf in TF_LIST:

    gene_idx = np.where(gene_symbols.values == tf)[0]

    if len(gene_idx) != 1:
        print(f"Skipping {tf}: {len(gene_idx)} matching genes")
        continue

    # Read only the TF's expression column
    x = adata[:, int(gene_idx[0])].X

    if sparse.issparse(x):
        x = x.toarray()

    x = np.asarray(x).ravel()

    for batch in obs["batch"].unique():

        batch_mask = obs["batch"].values == batch

        pert_mask = (
            batch_mask &
            (obs["TF"].values == tf)
        )

        ctrl_mask = (
            batch_mask &
            control_mask.values
        )

        pert = x[pert_mask]
        ctrl = x[ctrl_mask]

        if len(pert) < 20 or len(ctrl) < 20:
            continue

        p = mannwhitneyu(
            pert, ctrl, alternative="two-sided"
        ).pvalue

        results.append({
            "TF": tf,
            "Batch": batch,
            "Perturbed_Cells": len(pert),
            "Control_Cells": len(ctrl),
            "Perturbed_Mean": np.mean(pert),
            "Control_Mean": np.mean(ctrl),
            "Mean_Difference": np.mean(pert) - np.mean(ctrl),
            "P_Value": p
        })

summary = pd.DataFrame(results)

print("\nON-TARGET PERTURBATION CHECK")
print(summary.to_string(index=False))

adata.file.close()

