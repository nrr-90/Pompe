    sub = meta[
        meta["Condition"].isin(["Control", tf]) &
        meta["Group"].isin(groups)
    ].copy()

    guide_names = sorted(sub["Guide"].unique())

    targeting_guides = set(
        sub.loc[sub["Condition"] == tf, "Guide"]
    )

    n_target = len(targeting_guides)
    n_guides = len(guide_names)

    # Guide-by-group-by-gene expression matrix
    group_matrices = []

    for group in groups:

        group_sub = sub[sub["Group"] == group]

        indices = [
            group_sub.index[
                group_sub["Guide"] == guide
            ][0]
            for guide in guide_names
        ]

