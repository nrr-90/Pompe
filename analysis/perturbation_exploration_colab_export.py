def get_mean_expression(cell_indices, gene_indices):
    """Read only requested rows/columns from the backed matrix."""
    if len(cell_indices) == 0:
        return np.full(len(gene_indices), np.nan)

    # Sorted unique indices ensure reliable backed slicing
    cell_indices = np.sort(np.asarray(cell_indices, dtype=int))
    gene_indices = np.asarray(gene_indices, dtype=int)

    # Read rows first to avoid dense full-matrix loading
    X = adata.X[cell_indices, :]
    X = X[:, gene_indices]

    if sparse.issparse(X):
        return np.asarray(X.mean(axis=0)).ravel()

    return np.asarray(X).mean(axis=0).ravel()

