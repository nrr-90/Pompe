def exact_guide_permutation(sub, groups):

    sub = sub[sub["cluster"].isin(groups)].copy()

    # Each guide must be present in every selected group
    pivot = sub.pivot_table(
        index="guide",
        columns="cluster",
        values="Mean_Expression"
    )

    pivot = pivot.dropna(subset=groups)
    pivot = pivot[groups]

    targeting = sorted(
        set(sub.loc[sub["condition"] != "Control", "guide"])
    )

    controls = sorted(
        set(sub.loc[sub["condition"] == "Control", "guide"])
    )

    guide_names = pivot.index.tolist()

    if not set(targeting + controls).issubset(guide_names):
        return None

    values = pivot.to_numpy()
    n_target = len(targeting)

    def statistic(selected_indices):
        selected_indices = np.array(selected_indices)

        remaining = np.array([
            i for i in range(len(guide_names))
            if i not in selected_indices
        ])

        # Equal weighting across guides and experimental groups
        return (
            values[selected_indices].mean(axis=0)
            - values[remaining].mean(axis=0)
        ).mean()

    observed_indices = [
        guide_names.index(g) for g in targeting
    ]

    observed = statistic(observed_indices)

    null = np.array([
        statistic(indices)
        for indices in itertools.combinations(
            range(len(guide_names)), n_target
        )
    ])

    p_two_sided = np.mean(
        np.abs(null) >= abs(observed) - 1e-12
    )

    return {
        "Observed_Effect": observed,
        "Permutation_P": p_two_sided,
        "N_Target_Guides": n_target,
        "N_Control_Guides": len(controls),
        "N_Permutations": len(null)
    }


results = []

for (tf, target), sub in data.groupby(["TF", "Target"]):

    primary = exact_guide_permutation(
        sub, ["tfs_7", "tfs_13"]
    )

    sensitivity = exact_guide_permutation(
        sub, ["tfs_7", "tfs_13", "tfs_highmoi"]
    )

    if primary is None or sensitivity is None:
        continue

    results.append({
        "TF": tf,
        "Target": target,
        "Standard_Effect": primary["Observed_Effect"],
        "Standard_P": primary["Permutation_P"],
        "All_Groups_Effect": sensitivity["Observed_Effect"],
        "All_Groups_P": sensitivity["Permutation_P"],
        "N_Target_Guides": primary["N_Target_Guides"],
        "N_Control_Guides": primary["N_Control_Guides"],
        "N_Permutations": primary["N_Permutations"]
    })

results = pd.DataFrame(results)

# Multiple-testing correction across the 14 candidate edges
