def partial_spearman(x, y, covariates):
    """
    Rank-transform variables, regress x and y separately
    on ranked covariates, then correlate residuals.
    """

    x = rankdata(np.asarray(x, dtype=float))
    y = rankdata(np.asarray(y, dtype=float))

    Z = np.column_stack([
        np.ones(len(x)),
        *[
            rankdata(np.asarray(c, dtype=float))
            for c in covariates
        ]
    ])

    rx = x - Z @ np.linalg.lstsq(Z, x, rcond=None)[0]
    ry = y - Z @ np.linalg.lstsq(Z, y, rcond=None)[0]

    return pearsonr(rx, ry).statistic

