def find_column(df, candidates):
    lookup = {
        c.lower().replace(" ", "").replace("_", ""): c
        for c in df.columns
    }

    for candidate in candidates:
        key = candidate.lower().replace(" ", "").replace("_", "")
        if key in lookup:
            return lookup[key]

    return None

tf_col = find_column(de, ["TF", "transcription_factor"])
