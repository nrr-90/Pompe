# ============================================================
# SELECT REPRESENTATIVE EDGES
# ============================================================
# Maximum number of edges allowed from the same TF.
# This prevents one regulator from dominating the entire figure.

MAX_PER_TF = 3
N_EDGES = 12

def select_diverse_edges(df, ascending):

    df = df.sort_values(
        "delta_treated_minus_disease",
        ascending=ascending
    ).copy()

    selected = []
    tf_count = {}

    for _, row in df.iterrows():

        tf = row["TF"]

        if tf_count.get(tf, 0) < MAX_PER_TF:
            selected.append(row)
            tf_count[tf] = tf_count.get(tf, 0) + 1

        if len(selected) >= N_EDGES:
            break

    return pd.DataFrame(selected)

# Most negative
dec_selected = select_diverse_edges(
    dec,
    ascending=True
)

# Most positive
inc_selected = select_diverse_edges(
    inc,
    ascending=False
)

