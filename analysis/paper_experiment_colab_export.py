import os
import pandas as pd
import numpy as np

# ============================================================
# Paths
# ============================================================

BASE = "/content/drive/MyDrive/MultiCausGRN_Pompe"

RESULT_DIR = f"{BASE}/pompe_gse159062/Result/Pompe_Treated/POMPE_GSE159062_Treated_genes6116_seed8"
INPUT_DIR = f"{BASE}/pompe_gse159062/processed/Pompe_VS_Treated"
OUT_DIR = f"{BASE}/Results/Pompe_Treated/FULL_NETWORK_DISCOVERY"

os.makedirs(OUT_DIR, exist_ok=True)

tf_embed_path = f"{RESULT_DIR}/tf_embedding.csv"
target_embed_path = f"{RESULT_DIR}/target_embedding.csv"

print("TF embedding:", tf_embed_path, os.path.exists(tf_embed_path))
print("Target embedding:", target_embed_path, os.path.exists(target_embed_path))
print("Output:", OUT_DIR)

# ============================================================
# Load embeddings and index files
# ============================================================

tf_embed = pd.read_csv(tf_embed_path, index_col=0)
target_embed = pd.read_csv(target_embed_path, index_col=0)

tf_indices = pd.read_csv(f"{INPUT_DIR}/TF.csv")["index"].astype(int).values
target_indices = pd.read_csv(f"{INPUT_DIR}/Target.csv")["index"].astype(int).values

gene_map = pd.read_csv(f"{INPUT_DIR}/gene_index_map.csv")
idx_to_gene = dict(zip(gene_map["index"].astype(int), gene_map["gene_symbol"].astype(str)))

print("TF embedding shape:", tf_embed.shape)
print("Target embedding shape:", target_embed.shape)
print("TFs:", len(tf_indices))
print("Targets:", len(target_indices))

# ============================================================
# Score all TF × target pairs
# ============================================================

tf_mat_all = tf_embed.values.astype("float32")
target_mat_all = target_embed.values.astype("float32")

tf_mat = tf_mat_all[tf_indices]
target_mat = target_mat_all[target_indices]

logits = tf_mat @ target_mat.T
scores = 1 / (1 + np.exp(-logits))

print("Logits range:", logits.min(), logits.max())
print("Score range:", scores.min(), scores.max())
print("Score matrix:", scores.shape)

# ============================================================
# Convert to long table
# ============================================================

tf_grid, target_grid = np.meshgrid(tf_indices, target_indices, indexing="ij")

all_scores = pd.DataFrame({
    "tf_idx": tf_grid.ravel(),
    "target_idx": target_grid.ravel(),
    "score": scores.ravel()
})

# remove self-loops
all_scores = all_scores[all_scores["tf_idx"] != all_scores["target_idx"]].copy()

all_scores["TF"] = all_scores["tf_idx"].map(idx_to_gene)
all_scores["Target"] = all_scores["target_idx"].map(idx_to_gene)

all_scores["edge_upper"] = (
    all_scores["TF"].astype(str).str.upper().str.strip()
    + "_"
    + all_scores["Target"].astype(str).str.upper().str.strip()
)

all_scores = all_scores.sort_values("score", ascending=False).reset_index(drop=True)

all_scores.to_csv(f"{OUT_DIR}/TRUE_all_TF_target_scores.csv", index=False)

print("All scored edges:", all_scores.shape)
display(all_scores[["TF", "Target", "score"]].head(20))

# ============================================================
# Remove complete TRRUST-positive set
# ============================================================

positive_edges = pd.read_csv(f"{INPUT_DIR}/Positive_edges.csv")

def idx_edges_to_names(df):
    df = df.copy()
    df["TF"] = df["tf_idx"].map(idx_to_gene).astype(str).str.upper().str.strip()
    df["Target"] = df["target_idx"].map(idx_to_gene).astype(str).str.upper().str.strip()
    df["edge_upper"] = df["TF"] + "_" + df["Target"]
    return df

positive_edges_named = idx_edges_to_names(positive_edges)
positive_set = set(positive_edges_named["edge_upper"])

all_scores["in_positive_TRRUST_filtered"] = all_scores["edge_upper"].isin(positive_set)

known_edges = all_scores[all_scores["in_positive_TRRUST_filtered"]].copy()
novel_edges = all_scores[~all_scores["in_positive_TRRUST_filtered"]].copy()

known_edges = known_edges.sort_values("score", ascending=False).reset_index(drop=True)
novel_edges = novel_edges.sort_values("score", ascending=False).reset_index(drop=True)

known_edges.to_csv(f"{OUT_DIR}/TRUE_known_TRRUST_edges_ranked.csv", index=False)
novel_edges.to_csv(f"{OUT_DIR}/TRUE_novel_edges_ranked.csv", index=False)

print("Known TRRUST-positive edges:", known_edges.shape)
print("True novel edges:", novel_edges.shape)

print("\nTop known edges:")
display(known_edges[["TF", "Target", "score"]].head(20))

print("\nTop true novel edges:")
display(novel_edges[["TF", "Target", "score"]].head(50))

# ============================================================
# Top edges and hub TFs
# ============================================================

TOP_N = 1000

top_all = all_scores.head(TOP_N).copy()
top_known = known_edges.head(TOP_N).copy()
top_novel = novel_edges.head(TOP_N).copy()

top_all.to_csv(f"{OUT_DIR}/TRUE_top{TOP_N}_all_edges.csv", index=False)
top_known.to_csv(f"{OUT_DIR}/TRUE_top{TOP_N}_known_edges.csv", index=False)
top_novel.to_csv(f"{OUT_DIR}/TRUE_top{TOP_N}_novel_edges.csv", index=False)

hub_all = (
    top_all.groupby("TF")
    .agg(
        score_sum=("score", "sum"),
        score_mean=("score", "mean"),
        n_edges=("Target", "count")
    )
    .reset_index()
    .sort_values(["score_sum", "n_edges"], ascending=False)
)

hub_novel = (
    top_novel.groupby("TF")
    .agg(
        score_sum=("score", "sum"),
        score_mean=("score", "mean"),
        n_edges=("Target", "count")
    )
    .reset_index()
    .sort_values(["score_sum", "n_edges"], ascending=False)
)

hub_all.to_csv(f"{OUT_DIR}/TRUE_top{TOP_N}_hub_TFs_all.csv", index=False)
hub_novel.to_csv(f"{OUT_DIR}/TRUE_top{TOP_N}_hub_TFs_novel.csv", index=False)

print("Top hub TFs overall:")
display(hub_all.head(20))

print("Top hub TFs novel:")
display(hub_novel.head(20))

