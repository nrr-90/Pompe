def make_split(pos_df, neg_df):

    pos_l = pos_df.copy()
    pos_l["label"] = 1

    neg_l = neg_df.copy()
    neg_l["label"] = 0

    out = pd.concat(
        [pos_l, neg_l],
        axis=0
    )

    out = out.sample(
        frac=1,
        random_state=8
    ).reset_index(drop=True)

    return out[
        ["tf_idx", "target_idx", "label"]
    ]

