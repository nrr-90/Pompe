import pandas as pd
import numpy as np
import networkx as nx
import matplotlib.pyplot as plt

rep = pd.read_csv(
    f"{VAL}/Replicated_Top1000_Novel_Edges.csv"
)

# ============================================================
# SELECT REPRESENTATIVE REPLICATED EDGES
# ============================================================

# Smaller combined rank = stronger replication
rep["combined_rank"] = (
    rep["common_rank_GSE159062"] +
    rep["common_rank_GSE38680"]
)

rep = rep.sort_values(
    "combined_rank"
).reset_index(drop=True)

MAX_PER_TF = 5
N_EDGES = 25

selected = []
tf_counts = {}

for _, row in rep.iterrows():

    tf = row["TF"]

    if tf_counts.get(tf, 0) >= MAX_PER_TF:
        continue

    selected.append(row)
    tf_counts[tf] = tf_counts.get(tf, 0) + 1

    if len(selected) >= N_EDGES:
        break

net = pd.DataFrame(selected)

print("Edges displayed:", len(net))

print(
    net[
        [
            "TF",
            "Target",
            "common_rank_GSE159062",
            "common_rank_GSE38680"
        ]
    ].to_string(index=False)
)

# ============================================================
# NETWORK
# ============================================================

G = nx.DiGraph()

for _, row in net.iterrows():

    G.add_edge(
        row["TF"],
        row["Target"]
    )

tf_nodes = set(net["TF"])

target_nodes = (
    set(net["Target"]) - tf_nodes
)

# Fixed layout for reproducibility
pos = nx.spring_layout(
    G,
    seed=8,
    k=1.25,
    iterations=300
)

fig, ax = plt.subplots(
    figsize=(9.5, 8)
)

# TF nodes
nx.draw_networkx_nodes(
    G,
    pos,
    nodelist=list(tf_nodes),
    node_size=1500,
    ax=ax
)

# Target-only nodes
nx.draw_networkx_nodes(
    G,
    pos,
    nodelist=list(target_nodes),
    node_size=650,
    ax=ax
)

# Edges
nx.draw_networkx_edges(
    G,
    pos,
    arrows=True,
    arrowstyle="-|>",
    arrowsize=15,
    width=1.2,
    alpha=0.65,
    connectionstyle="arc3,rad=0.04",
    ax=ax
)

# Labels
nx.draw_networkx_labels(
    G,
    pos,
    font_size=8.5,
    font_weight="bold",
    ax=ax
)

ax.axis("off")

plt.tight_layout()

plt.savefig(
    f"{FIG}/Figure5C_Replicated_Regulatory_Network.png",
    dpi=600,
    bbox_inches="tight"
)

plt.savefig(
    f"{FIG}/Figure5C_Replicated_Regulatory_Network.pdf",
    bbox_inches="tight"
)

plt.show()

