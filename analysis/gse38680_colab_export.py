# BUILD AVAILABLE TARGETS FOR EACH TF
# ============================================================

tf_to_targets = (
    rank_merge
    .groupby("TF")["Target"]
    .apply(lambda x: np.asarray(x.unique()))
    .to_dict()
)

# Number of top-1000 GSE38680 edges contributed by each TF
tf_counts = (
    top2.groupby("TF")
    .size()
    .to_dict()
)

print("TFs represented in GSE38680 Top-1000:", len(tf_counts))

# ============================================================
# TF-STRUCTURE-PRESERVING PERMUTATION
# ============================================================

N_PERM = 10000
rng = np.random.default_rng(8)

null_overlaps = np.zeros(N_PERM, dtype=int)

for i in range(N_PERM):

    random_edges = set()

    for tf, n_edges in tf_counts.items():

        targets = tf_to_targets[tf]

        n_select = min(n_edges, len(targets))

        sampled_targets = rng.choice(
            targets,
            size=n_select,
            replace=False
        )

        random_edges.update(
            f"{tf}→{target}"
            for target in sampled_targets
        )

    null_overlaps[i] = len(
        set1 & random_edges
    )

